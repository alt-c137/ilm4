function fingerprint(sdp: string | undefined): string {
  const m = /a=fingerprint:sha-256 ([0-9A-Fa-f:]+)/.exec(sdp || '');
  return m ? m[1].replace(/:/g, '').toUpperCase() : '';
}

export async function callEmoji(localSdp?: string, remoteSdp?: string): Promise<string[]> {
  const a = fingerprint(localSdp);
  const b = fingerprint(remoteSdp);
  if (!a || !b) return [];
  const hex = await Crypto.digestStringAsync(Crypto.CryptoDigestAlgorithm.SHA256, a < b ? `${a}|${b}` : `${b}|${a}`);
  return [0, 1, 2, 3].map((i) => CALL_EMOJI[parseInt(hex.slice(i * 2, i * 2 + 2), 16) % 128]);
}
