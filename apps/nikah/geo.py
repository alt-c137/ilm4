_LANG_INDEX = {'en': 0, 'uz': 1}
_REVERSE = {name.lower(): ru for ru, names in COUNTRY_I18N.items() for name in (ru, *names)}


def country_name(ru_name: str, lang: str) -> str:
    """Русское название из базы → на языке интерфейса."""
    i = _LANG_INDEX.get(lang)
    return COUNTRY_I18N.get(ru_name, (ru_name, ru_name))[i] if i is not None and ru_name else ru_name


def canonical_country(name: str) -> str:
    """Любое название (рус/англ/узб, в любом регистре) → русское, как хранится в базе."""
    return _REVERSE.get((name or '').strip().lower(), (name or '').strip())


def countries_for(lang: str) -> list:
    return sorted((country_name(c, lang) for c in COUNTRIES), key=lambda s: s.lower())
